package research

import "testing"

func TestDetectWAF(t *testing.T) {
	tests := []struct {
		name    string
		headers map[string][]string
		body    string
		want    string
	}{
		{
			name:    "cloudflare via cf-ray header",
			headers: map[string][]string{"Cf-Ray": {"7d1b2c3d4e5f-GRU"}, "Server": {"cloudflare"}},
			want:    "cloudflare",
		},
		{
			name:    "akamai via server",
			headers: map[string][]string{"Server": {"AkamaiGHost"}},
			want:    "akamai",
		},
		{
			name:    "sucuri via x-sucuri-id",
			headers: map[string][]string{"X-Sucuri-ID": {"12345"}},
			want:    "sucuri",
		},
		{
			name:    "imperva via x-iinfo",
			headers: map[string][]string{"X-Iinfo": {"1-2-3"}},
			want:    "imperva-incapsula",
		},
		{
			name:    "fortiweb via cookie",
			headers: map[string][]string{"Set-Cookie": {"FORTIWAFSID=abc; path=/"}},
			want:    "fortiweb",
		},
		{
			name: "wordfence via body",
			body: "<html>Generated by Wordfence</html>",
			want: "wordfence",
		},
		{
			name:    "no waf",
			headers: map[string][]string{"Server": {"nginx"}},
			body:    "<html>hello</html>",
			want:    "",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := DetectWAF(tt.headers, []byte(tt.body))
			if got != tt.want {
				t.Errorf("DetectWAF = %q, want %q", got, tt.want)
			}
		})
	}
}

func TestDetectWAFHeaderCaseInsensitive(t *testing.T) {
	// Header names arrive in varied casing; matching must be case-insensitive.
	got := DetectWAF(map[string][]string{"SERVER": {"CLOUDFLARE"}}, nil)
	if got != "cloudflare" {
		t.Errorf("case-insensitive match failed: got %q", got)
	}
}
