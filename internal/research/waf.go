package research

import (
	"regexp"
	"strings"
)

// wafSignature matches a WAF/CDN-security product from response evidence. A
// signature fires when any of its header checks or body patterns match.
type wafSignature struct {
	name string
	// headers maps a (lowercased) header name to a substring that must appear
	// in that header's value. An empty substring means "header present".
	headers map[string]string
	// bodyPatterns are compiled regexes matched against the response body.
	bodyPatterns []*regexp.Regexp
}

// wafSignatures recovers the WAF-fingerprinting capability surveyed from the
// l0ners fork, as a response-evidence table. This classifies by observable
// response markers (headers, cookies, block pages) and is independent of the
// IP-range cdncheck used by -cdn.
//
// shortcut: curated signature set (the common public WAFs), upgrade when a
// target WAF is missed — add its header/body markers here.
var wafSignatures = []wafSignature{
	{name: "cloudflare", headers: map[string]string{"server": "cloudflare", "cf-ray": ""}},
	{name: "akamai", headers: map[string]string{"server": "akamaighost", "x-akamai-transformed": ""}},
	{name: "sucuri", headers: map[string]string{"server": "sucuri", "x-sucuri-id": "", "x-sucuri-cache": ""}},
	{name: "imperva-incapsula", headers: map[string]string{"x-iinfo": "", "x-cdn": "incapsula"}},
	{name: "aws-waf", headers: map[string]string{"x-amzn-waf-action": "", "x-amz-cf-id": ""}},
	{name: "f5-big-ip", headers: map[string]string{"server": "big-ip", "x-waf-event-info": ""}},
	{name: "fortiweb", headers: map[string]string{"set-cookie": "fortiwafsid"}},
	{name: "barracuda", headers: map[string]string{"set-cookie": "barra_counter_session"}},
	{
		name:         "wordfence",
		bodyPatterns: []*regexp.Regexp{regexp.MustCompile(`(?i)generated by wordfence`)},
	},
}

// DetectWAF returns the first WAF/security product whose signature matches the
// response headers/body, or "" when none match. Header keys are matched
// case-insensitively.
func DetectWAF(headers map[string][]string, body []byte) string {
	lower := lowerHeaders(headers)
	bodyStr := string(body)
	for _, sig := range wafSignatures {
		if sig.matchHeaders(lower) || sig.matchBody(bodyStr) {
			return sig.name
		}
	}
	return ""
}

func (s wafSignature) matchHeaders(lower map[string]string) bool {
	for name, want := range s.headers {
		val, ok := lower[name]
		if !ok {
			continue
		}
		if want == "" || strings.Contains(val, want) {
			return true
		}
	}
	return false
}

func (s wafSignature) matchBody(body string) bool {
	for _, re := range s.bodyPatterns {
		if re.MatchString(body) {
			return true
		}
	}
	return false
}

// lowerHeaders flattens headers into a lowercased name -> joined,lowercased
// value map for case-insensitive matching.
func lowerHeaders(headers map[string][]string) map[string]string {
	out := make(map[string]string, len(headers))
	for k, v := range headers {
		out[strings.ToLower(k)] = strings.ToLower(strings.Join(v, " "))
	}
	return out
}
